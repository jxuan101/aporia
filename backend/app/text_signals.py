def normalized_words(value: str) -> tuple[str, ...]:
    normalized = unicodedata.normalize("NFKC", value).casefold()
    return tuple(TOKEN_PATTERN.findall(normalized))


def meaningful_terms(value: str) -> set[str]:
    return {term for term in normalized_words(value) if term not in STOP_WORDS}
